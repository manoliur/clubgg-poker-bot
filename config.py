def nick_zone(seat):
    """Зона ника места в долях (x0,y0,x1,y1). seat: 0 — герой, 1..5 по кругу.

    None — такого места нет (чужой индекс не должен ронять чтение кадра).
    """
    try:
        seat = int(seat)
    except (TypeError, ValueError):
        return None
    return NICK_ZONES[seat] if 0 <= seat < len(NICK_ZONES) else None


def seat_at(x, y, img_w, img_h):
    """Место (0 — герой, 1..5 по кругу), чья плашка ближе всего к точке (x, y).

    Нужно потому, что клиент сажает игроков по-разному: номер плашки по кругу
    («второй от героя») ничего не говорит о том, ГДЕ она нарисована, а зона ника
    привязана именно к месту на экране.
    """
    if not img_w or not img_h:
        return None
    best, best_d = None, None
    for i, zone in enumerate(SEAT_ZONES):
        cx = (zone[0] + zone[2]) / 2 * img_w
        cy = (zone[1] + zone[3]) / 2 * img_h
        d = ((x - cx) / img_w) ** 2 + ((y - cy) / img_h) ** 2
        if best_d is None or d < best_d:
            best, best_d = i, d
    return best if best_d is not None and best_d <= SEAT_MATCH_DIST ** 2 else None


def rect_px(rect, img_w, img_h):
    """Эталонный прямоугольник (x0,y0,x1,y1) в пикселях 1080x2400 -> под скриншот."""
    x0, y0 = scale(rect[:2], img_w, img_h)
    x1, y1 = scale(rect[2:], img_w, img_h)
    return (x0, y0, x1, y1)
