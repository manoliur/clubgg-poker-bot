def tap_point(frac, img_w, img_h):
    """Точка тапа из долей экрана -> пиксели кадра img_w x img_h.

    Единственный способ получить координату тапа: доли умножаются на ФАКТИЧЕСКИЙ
    размер кадра (он же размер экрана — screencap отдаёт его как есть), а не на
    эталонные 1080x2400. Так одна и та же точка попадает в кнопку и на 2400, и
    на 2340 (185, 2315) -> (185, 2257).
    """
    fx, fy = frac
    return int(round(fx * img_w)), int(round(fy * img_h))


def scale(pt, img_w, img_h):
    """Эталонная координата -> координата для скриншота размера img_w x img_h."""
    x, y = pt
    return int(round(x * img_w / REF_W)), int(round(y * img_h / REF_H))


def zone_px(zone, img_w, img_h):
    """Доли (x0,y0,x1,y1) -> пиксели (x0,y0,x1,y1)."""
    x0, y0, x1, y1 = zone
    return (int(x0 * img_w), int(y0 * img_h), int(x1 * img_w), int(y1 * img_h))


