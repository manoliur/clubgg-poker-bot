def scale(pt, img_w, img_h):
    """Эталонная координата -> координата для скриншота размера img_w x img_h."""
    x, y = pt
    return int(round(x * img_w / REF_W)), int(round(y * img_h / REF_H))


def zone_px(zone, img_w, img_h):
    """Доли (x0,y0,x1,y1) -> пиксели (x0,y0,x1,y1)."""
    x0, y0, x1, y1 = zone
    return (int(x0 * img_w), int(y0 * img_h), int(x1 * img_w), int(y1 * img_h))


def call_amount_rect():
    """Зона жёлтой суммы на кнопке «Колл» в долях (x0,y0,x1,y1)."""
    return (CALL_AMOUNT_X[0] / REF_W, ACTION_BAR_Y[0], CALL_AMOUNT_X[1] / REF_W, ACTION_BAR_Y[1])


def preset_rect(i):
    """Зона i-й строки столбца ставки (0 — нижняя, сама кнопка «Бет») в долях."""
    y0, y1 = PRESET_ROWS[i]
    return (PRESET_X[0] / REF_W, y0 / REF_H, PRESET_X[1] / REF_W, y1 / REF_H)


def rect_px(rect, img_w, img_h):
    """Эталонный прямоугольник (x0,y0,x1,y1) в пикселях 1080x2400 -> под скриншот."""
    x0, y0 = scale(rect[:2], img_w, img_h)
    x1, y1 = scale(rect[2:], img_w, img_h)
    return (x0, y0, x1, y1)
